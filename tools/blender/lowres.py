"""Half-size lightmaps for Low graphics and weak devices.

Every baked set's lightmap (2048²) gets a 1024² sibling, `<name>-1k.webp`,
recorded as `lightmapLow` next to `lightmap` in the manifest. The client picks
it on Low (or Auto on a weak device): a quarter of the download and of the GPU
memory, and baked light is soft enough that it barely shows.

blib.record() calls `add_low_variants` for every entry it writes, so a fresh
bake gets its variant automatically. For the lightmaps already in the repo,
run it on its own (needs only Pillow, not Blender):

    python3 tools/blender/lowres.py
"""

from __future__ import annotations

import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
PUBLIC = os.path.join(REPO, 'client', 'public')
MANIFEST = os.path.join(HERE, 'manifest.json')
ASSETS_TS = os.path.join(REPO, 'client', 'src', 'three', 'assets.gen.ts')

LOW_SIZE = 1024
LOW_QUALITY = 88


def _hash(path: str) -> str:
    with open(path, 'rb') as f:
        return hashlib.sha1(f.read()).hexdigest()[:10]


def low_path(url: str) -> str:
    """'/models/x/room-light.webp?v=…' → '/models/x/room-light-1k.webp'."""
    base = url.split('?')[0]
    stem, ext = os.path.splitext(base)
    return f'{stem}-1k{ext}'


def write_low(url: str) -> str:
    """Write the half-size copy of a lightmap; returns its URL with a content hash."""
    from PIL import Image

    src = os.path.join(PUBLIC, url.split('?')[0].lstrip('/'))
    dst_url = low_path(url)
    dst = os.path.join(PUBLIC, dst_url.lstrip('/'))
    with Image.open(src) as im:
        im = im.convert('RGB')
        w, h = im.size
        scale = min(1.0, LOW_SIZE / max(w, h))
        small = im.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
        small.save(dst, 'WEBP', quality=LOW_QUALITY, method=6)
    print('[lowres] wrote', os.path.relpath(dst, REPO), f'{os.path.getsize(dst) // 1024} KB')
    return f'{dst_url}?v={_hash(dst)}'


def add_low_variants(entry: dict) -> dict:
    """An entry with a 'lightmap' gains 'lightmapLow' (written fresh from the current lightmap)."""
    if isinstance(entry.get('lightmap'), str):
        entry = {**entry, 'lightmapLow': write_low(entry['lightmap'])}
    return entry


def write_assets_ts(data: dict) -> None:
    lines = [
        '// Generated by tools/blender (blib.record) — do not edit by hand.',
        '// URLs carry a content hash so a rebuilt asset is never served stale.',
        '',
        f'export const ASSETS = {json.dumps(data, indent=2, sort_keys=True)} as const;',
        '',
    ]
    with open(ASSETS_TS, 'w') as f:
        f.write('\n'.join(lines))


def main() -> None:
    with open(MANIFEST) as f:
        data = json.load(f)
    for key, entry in data.items():
        data[key] = add_low_variants(entry)
    with open(MANIFEST, 'w') as f:
        json.dump(data, f, indent=2, sort_keys=True)
        f.write('\n')
    write_assets_ts(data)
    print('[lowres] manifest and assets.gen.ts updated')


if __name__ == '__main__':
    main()
